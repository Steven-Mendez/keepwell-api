// Builds the views into one self-contained HTML file and writes it, as a string constant, into the
// API's src/entrypoints/mcp/ui/views.generated.ts. The API never builds UI: it imports that file, so
// `pnpm dev`, the tests and esbuild need nothing extra. CI rebuilds it and fails on any difference.
import { execFileSync } from "node:child_process"
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const out = join(root, "..", "src", "entrypoints", "mcp", "ui", "views.generated.ts")

execFileSync("pnpm", ["exec", "vite", "build", "--logLevel", "error"], { cwd: root, stdio: "inherit" })
const html = readFileSync(join(root, "dist", "index.html"), "utf8")
writeFileSync(
  out,
  [
    "// Generated by mcp-ui/scripts/build.mjs from mcp-ui/src. Do not edit: change the views and run `pnpm build:ui`.",
    "/* eslint-disable */",
    "",
    `export const VIEWS_HTML = ${JSON.stringify(html)}`,
    "",
  ].join("\n")
)
console.log(`mcp-ui: ${(html.length / 1024).toFixed(0)} KiB → ${out}`)
